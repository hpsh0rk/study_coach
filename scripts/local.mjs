#!/usr/bin/env node
// Local launcher for both run modes. Data lives in apps/app/.wrangler/state; the AI_CONFIG_KEY that seals
// keys stored in D1 is generated once into apps/app/.wrangler/kj-local.env, next to the data it protects.
//   node scripts/local.mjs start [--stub] [-- <wrangler dev args>]   production settings (pnpm start:local)
//   node scripts/local.mjs dev   [-- <wrangler dev args>]            development settings, stub model on (pnpm dev)
// Pending migrations are applied before every start, so pulling a new version needs no extra step.
import { execFileSync, spawn } from "node:child_process";
import { webcrypto as crypto, randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = resolve(root, "apps/app");
const stateDir = resolve(appDir, ".wrangler/state");
const secretsFile = resolve(appDir, ".wrangler/kj-local.env");
/** What `secret()` used to fall back to outside production; values sealed with it are re-sealed once. */
const LEGACY_KEY = "kj-local-development-only:AI_CONFIG_KEY";

const [mode, ...rest] = process.argv.slice(2);
const split = rest.indexOf("--");
const own = split < 0 ? rest : rest.slice(0, split);
const passthrough = split < 0 ? [] : rest.slice(split + 1);
if (mode !== "start" && mode !== "dev") {
  console.error("usage: node scripts/local.mjs start|dev [--stub] [-- <wrangler dev args>]");
  process.exit(2);
}
const allowStub = mode === "dev" || own.includes("--stub");

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: "inherit", ...opts });
const wrangler = (args, opts = {}) => execFileSync("npx", ["wrangler", ...args], { cwd: appDir, encoding: "utf8", ...opts });

function ensureSecret() {
  if (existsSync(secretsFile)) {
    const key = /^AI_CONFIG_KEY=(.+)$/m.exec(readFileSync(secretsFile, "utf8"))?.[1]?.trim();
    if (!key) throw new Error(`${secretsFile} has no AI_CONFIG_KEY line`);
    return { key, created: false };
  }
  mkdirSync(dirname(secretsFile), { recursive: true });
  const key = randomBytes(32).toString("base64url");
  writeFileSync(secretsFile, `# Generated by scripts/local.mjs. Seals the keys saved in 后台; losing it means re-entering them.\nAI_CONFIG_KEY=${key}\n`, { mode: 0o600 });
  chmodSync(secretsFile, 0o600);
  console.log(`Generated a local AI_CONFIG_KEY in ${secretsFile}`);
  return { key, created: true };
}

// Same format as packages/ai/src/secrets.ts.
const enc = new TextEncoder();
const aesKey = async (secret) => crypto.subtle.importKey("raw", await crypto.subtle.digest("SHA-256", enc.encode(secret)), "AES-GCM", false, ["encrypt", "decrypt"]);
async function open(sealed, secret) {
  const [v, iv, ct] = sealed.split(".");
  if (v !== "v1" || !iv || !ct) throw new Error("unsupported sealed secret");
  return new TextDecoder().decode(await crypto.subtle.decrypt({ name: "AES-GCM", iv: Buffer.from(iv, "base64") }, await aesKey(secret), Buffer.from(ct, "base64")));
}
async function seal(plain, secret) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, await aesKey(secret), enc.encode(plain)));
  return `v1.${Buffer.from(iv).toString("base64")}.${Buffer.from(ct).toString("base64")}`;
}

const SEALED = [
  { table: "ai_providers", key: "id", columns: ["api_key_sealed", "headers_sealed"] },
  { table: "parser_settings", key: "org_id", columns: ["mineru_token_sealed", "selfhost_url_sealed", "selfhost_key_sealed"] },
];
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const d1 = (sql) => JSON.parse(wrangler(["d1", "execute", "DB", "--local", "--persist-to", stateDir, "--json", "--command", sql], { stdio: ["ignore", "pipe", "inherit"] }))[0]?.results ?? [];

/** Keys saved before this launcher existed were sealed with the public development key: re-seal them with the new one. */
async function resealLegacy(key) {
  let moved = 0;
  for (const { table, key: pk, columns } of SEALED) {
    for (const row of d1(`SELECT ${pk}, ${columns.join(", ")} FROM ${table}`)) {
      const set = [];
      for (const col of columns) {
        if (!row[col]) continue;
        const plain = await open(row[col], LEGACY_KEY).catch(() => null);
        if (plain !== null) set.push(`${col} = ${q(await seal(plain, key))}`);
      }
      if (set.length) {
        d1(`UPDATE ${table} SET ${set.join(", ")} WHERE ${pk} = ${q(row[pk])}`);
        moved += set.length;
      }
    }
  }
  if (moved) console.log(`Re-sealed ${moved} saved key(s) with the new local AI_CONFIG_KEY. Old share links stop working; create new ones.`);
}

const { key, created } = ensureSecret();
run("pnpm", ["--filter", "@kj/web", "build"], { cwd: root });
wrangler(["d1", "migrations", "apply", "DB", "--local", "--persist-to", stateDir], { stdio: "inherit", env: { ...process.env, CI: "true" } });
if (created) await resealLegacy(key);

const vars = mode === "dev" ? ["--var", "ENVIRONMENT:development"] : [];
if (allowStub) vars.push("--var", "AI_ALLOW_STUB:true");
console.log(mode === "dev" ? "Development mode: stub model on when no provider is configured." : `Production settings${allowStub ? " (stub model explicitly on)" : ""}.`);
// --env-file also stops wrangler from reading a stray .dev.vars.
const child = spawn("npx", ["wrangler", "dev", "--persist-to", stateDir, "--env-file", secretsFile, ...vars, ...passthrough], { cwd: appDir, stdio: "inherit" });
child.on("exit", (code) => process.exit(code ?? 0));
